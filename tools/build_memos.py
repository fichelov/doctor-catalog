import os
from docx import Document
from docx.shared import Pt, Cm, RGBColor
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.oxml import OxmlElement
from docx.oxml.ns import qn

BASE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(BASE, 'assets', 'memos', '_src')
os.makedirs(SRC, exist_ok=True)

TEAL = RGBColor(0x0E, 0x6E, 0x68)
INK = RGBColor(0x17, 0x28, 0x2A)
GREY = RGBColor(0x6B, 0x7C, 0x7B)


def rich(par, text, size=10.5, bold=False, color=INK):
    run = par.add_run(text)
    run.font.name = 'Arial'
    run.font.size = Pt(size)
    run.font.bold = bold
    run.font.color.rgb = color
    rpr = run._element.get_or_add_rPr()
    rf = rpr.find(qn('w:rFonts'))
    if rf is None:
        rf = OxmlElement('w:rFonts'); rpr.append(rf)
    for a in ('w:ascii', 'w:hAnsi', 'w:cs', 'w:eastAsia'):
        rf.set(qn(a), 'Arial')
    return run


def shade(cell, fill):
    tcpr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement('w:shd')
    shd.set(qn('w:val'), 'clear'); shd.set(qn('w:color'), 'auto'); shd.set(qn('w:fill'), fill)
    tcpr.append(shd)


def borders(table):
    tblpr = table._tbl.tblPr
    b = OxmlElement('w:tblBorders')
    for edge in ('top', 'left', 'bottom', 'right', 'insideH', 'insideV'):
        el = OxmlElement(f'w:{edge}')
        el.set(qn('w:val'), 'single'); el.set(qn('w:sz'), '4')
        el.set(qn('w:space'), '0'); el.set(qn('w:color'), 'D8E2DF')
        b.append(el)
    tblpr.append(b)


def build_memo(spec):
    doc = Document()
    sec = doc.sections[0]
    sec.page_width = Cm(21); sec.page_height = Cm(29.7)
    sec.top_margin = Cm(1.7); sec.bottom_margin = Cm(1.5)
    sec.left_margin = Cm(1.9); sec.right_margin = Cm(1.9)

    st = doc.styles['Normal']
    st.font.name = 'Arial'; st.font.size = Pt(10.5); st.font.color.rgb = INK
    st.paragraph_format.space_after = Pt(4)
    st.paragraph_format.line_spacing = 1.12

    p = doc.add_paragraph()
    rich(p, 'ПРИЛОЖЕНИЕ ДЛЯ ВРАЧЕЙ  ·  ПАМЯТКА ДЛЯ СПЕЦИАЛИСТОВ', 8.5, True, TEAL)
    p.paragraph_format.space_after = Pt(2)

    p = doc.add_paragraph()
    rich(p, spec['title'], 19, True, TEAL)
    p.paragraph_format.space_after = Pt(2)

    p = doc.add_paragraph()
    rich(p, spec['subtitle'], 10, False, GREY)
    p.paragraph_format.space_after = Pt(10)

    p = doc.add_paragraph()
    rich(p, spec['intro'], 10.5)
    p.paragraph_format.space_after = Pt(8)

    for s in spec['sections']:
        h = doc.add_paragraph()
        rich(h, s['title'], 12, True, TEAL)
        h.paragraph_format.space_before = Pt(10)
        h.paragraph_format.space_after = Pt(3)
        for para_text in s.get('paras', []):
            pp = doc.add_paragraph()
            rich(pp, para_text, 10.5)
        for b in s.get('bullets', []):
            bp = doc.add_paragraph(style='List Bullet')
            bp.paragraph_format.space_after = Pt(2)
            bp.paragraph_format.left_indent = Cm(0.6)
            rich(bp, b, 10.5)

    if spec.get('table'):
        t = spec['table']
        table = doc.add_table(rows=1, cols=len(t['headers']))
        borders(table)
        for i, htxt in enumerate(t['headers']):
            cell = table.rows[0].cells[i]
            cell.text = ''
            rich(cell.paragraphs[0], htxt, 9, True, RGBColor(0xFF, 0xFF, 0xFF))
            shade(cell, '0E6E68')
        for row in t['rows']:
            cells = table.add_row().cells
            for i, val in enumerate(row):
                cells[i].text = ''
                rich(cells[i].paragraphs[0], val, 9)
        doc.add_paragraph().paragraph_format.space_after = Pt(0)

    if spec.get('outro'):
        p = doc.add_paragraph()
        rich(p, spec['outro'], 10.5)

    doc.add_paragraph()
    foot = doc.add_paragraph()
    rich(foot, 'Демонстрационный материал. Текст подлежит утверждению медицинским отделом компании '
               'перед публикацией. Не является инструкцией по применению.', 8, False, GREY)

    path = os.path.join(SRC, spec['id'] + '.docx')
    doc.save(path)
    return path


