/* Правила подбора: (ситуация, ответы) -> id продукта */
const NC_RULES = {
  lactation: ({ age, risk, symptom }) => {
    if (risk === 'yes') return age === '12-36' ? 'ntl-3' : (age === '0-6' ? 'ntl-ga-1' : 'ntl-ga-2');
    if (symptom === 'reflux') return age === '0-6' ? 'ntl-ar-1' : (age === '6-12' ? 'ntl-ar-2' : 'ntl-ar-komfort');
    if (symptom === 'constip') return age === '0-6' ? 'ntl-km-1' : (age === '6-12' ? 'ntl-km-2' : 'ntl-3');
    return age === '0-6' ? 'ntl-antikolik' : (age === '6-12' ? 'ntl-km-2' : 'ntl-3');
  },
  'no-milk': ({ age, risk, symptom }) => {
    if (risk === 'yes') return age === '0-6' ? 'ntl-ga-pepti-1' : (age === '6-12' ? 'ntl-ga-pepti-2' : 'ntl-3');
    if (symptom === 'reflux') return age === '0-6' ? 'ntl-ar-1' : (age === '6-12' ? 'ntl-ar-2' : 'ntl-ar-komfort');
    if (symptom === 'constip') return age === '0-6' ? 'ntl-1' : (age === '6-12' ? 'ntl-2' : 'ntl-3');
    return age === '0-6' ? 'ntl-1' : (age === '6-12' ? 'ntl-2' : 'ntl-3');
  },
  switch: ({ age, cause }) => {
    if (cause === 'allergy') {
      if (age === '0-6') return 'ntl-ga-pepti-1';
      if (age === '6-12') return 'ntl-ga-pepti-2';
      if (age === '12-24') return 'ntl-pepti-3';
      return 'ntl-soy-2';
    }
    if (cause === 'digest') {
      if (age === '0-6') return 'ntl-ar-1';
      if (age === '6-12') return 'ntl-ar-2';
      if (age === '12-24') return 'ntl-ar-komfort';
      return 'ntl-km-2';
    }
    if (cause === 'constip') {
      if (age === '0-6') return 'ntl-km-1';
      if (age === '6-12') return 'ntl-km-2';
      return 'ntl-3';
    }
    if (age === '0-6') return 'ntl-bl';
    return 'ntl-nl';
  },
  special: ({ case: cs, age, severity }) => {
    if (cs === 'preterm') {
      if (age === '0-6') return severity === 'severe' ? 'ntl-neo-pre' : 'ntl-neo-70';
      return 'ntl-neo-post';
    }
    if (cs === 'lowweight') {
      if (age === '0-6') return 'ntl-neo-70';
      return 'ntl-neo-post';
    }
    if (cs === 'reflux') {
      if (severity === 'severe') return 'ntl-ar-komfort';
      return age === '0-6' ? 'ntl-ar-1' : 'ntl-ar-2';
    }
    if (cs === 'allergy') {
      if (severity === 'severe') return age === '0-6' ? 'ntl-ga-pepti-1' : 'ntl-ga-pepti-2';
      if (age === '0-6') return 'ntl-ga-1';
      if (age === '6-12') return 'ntl-ga-2';
      return 'ntl-soy-2';
    }
    // lactase
    if (severity === 'severe') return 'ntl-bl';
    return 'ntl-nl';
  },
};
